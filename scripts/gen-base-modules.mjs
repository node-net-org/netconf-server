// Embed the base YANG modules the server needs and @node-net/yang doesn't bundle,
// so the Node-free core can compile them without a filesystem. modules/*.yang
// stays the source; this writes src/modules/base-modules.ts from it.
//
//   node scripts/gen-base-modules.mjs          write the file
//   node scripts/gen-base-modules.mjs --check  fail if it is out of date
//
// The build runs it, and a unit test fails if the committed file is stale.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const MODULES = fileURLToPath(new URL('../modules/', import.meta.url));
export const TARGET = fileURLToPath(new URL('../src/modules/base-modules.ts', import.meta.url));

/** The generated module's text. */
export function render() {
  const files = readdirSync(MODULES)
    .filter((n) => n.endsWith('.yang'))
    .sort();
  const entries = files.map((file) => `  { file: ${JSON.stringify(file)}, text: ${JSON.stringify(readFileSync(MODULES + file, 'utf8'))} },`);
  return [
    '// Generated by scripts/gen-base-modules.mjs from modules/*.yang. Do not edit.',
    '',
    '/** @internal The base modules: each file in modules/ and its text. */',
    'export const BASE_MODULES: readonly { readonly file: string; readonly text: string }[] = [',
    ...entries,
    '];',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render();
  if (process.argv.includes('--check')) {
    if (readFileSync(TARGET, 'utf8') !== text) {
      console.error('src/modules/base-modules.ts is out of date: run node scripts/gen-base-modules.mjs');
      process.exit(1);
    }
  } else {
    writeFileSync(TARGET, text);
  }
}
